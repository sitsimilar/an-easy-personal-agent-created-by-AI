/** 从条目名称中提取「可匹配的代码 token」（去掉中文注解，保留 ASCII 代码片段）。 */
function matchableTokens(name: string): string[] {
  return name
    .replace(/[\u4e00-\u9fa5（）()]/g, ' ') // 中文字符与中文括号替换为空格，保留括号内 ASCII 内容
    .split(/[/\s]+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && /[A-Za-z0-9_$<>.?[\]!&=+|%*^~-]/.test(s))
}

/** 判断单个 token 是否出现在代码中（词类用单词边界、符号类用子串）。 */
function tokenInCode(token: string, code: string): boolean {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(token)) {
    const re = new RegExp(`\\b${token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`)
    return re.test(code)
  }
  return code.includes(token)
}

/**
 * 从生成的代码中匹配速查库知识点（规则匹配，零额外 LLM 调用）。
 * 用于「代码生成」板块：展示代码涉及的关键字/运算符/语法/函数，并可跳转速查库详情。
 */
export function matchKnowledgePoints(code: string): CheatEntry[] {
  const out: CheatEntry[] = []
  const seen = new Set<string>()
  for (const e of CHEAT_ENTRIES) {
    const tokens = matchableTokens(e.name)
    if (tokens.some((t) => tokenInCode(t, code))) {
      if (!seen.has(e.id)) {
        seen.add(e.id)
        out.push(e)
      }
    }
  }
  return out
}
